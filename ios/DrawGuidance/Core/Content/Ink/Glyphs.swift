    static func allowed(_ c: CharClass, _ mode: InkMode) -> Bool {
        switch mode {
        case .MIXED: return true
        case .DIGITS: return c.cat == .DIGIT || c.cat == .SYMBOL || c.cat == .BRACKET || ".,:".contains(c.text)
        case .LETTERS: return c.cat == .LOWER || c.cat == .UPPER || c.cat == .PUNCT || c.cat == .BRACKET || c.text == "−"
        }
    }
