/// Harfin ana gövdesine eklenen küçük işaretler (nokta, iki nokta, kısa çizgi, çengel).
enum Marks { case NONE, DOT_ABOVE, TWO_DOTS_ABOVE, BREVE_ABOVE, CEDILLA_BELOW, DOT_BELOW, DOTS_ABOVE_BELOW, ONLY_DOT, ONLY_COLON, ONLY_TICK }

enum Cat { case DIGIT, LOWER, UPPER, SYMBOL, PUNCT, BRACKET }

/// Çıktı karakteri: kabul ettiği gövde şekil etiketleri, gereken işaretler, taslak kutusunun satırdaki yeri.
final class CharClass {
    let text: String
    let shapes: [String]
    let marks: Marks
    let top: Float
    let bottom: Float
    let cat: Cat
    let prior: Float
    let sigma: Float
    /// Gövdenin satırdaki sıkı bandı (taslakların gerçek y aralığından).
    var bandTop: Float
    var bandBottom: Float

    init(_ text: String, _ shapes: [String], _ marks: Marks, _ top: Float, _ bottom: Float, _ cat: Cat, _ prior: Float, _ sigma: Float = 0.12) {
        self.text = text; self.shapes = shapes; self.marks = marks; self.top = top; self.bottom = bottom
        self.cat = cat; self.prior = prior; self.sigma = sigma
        bandTop = top; bandBottom = bottom
    }
}

